-- ---------- Base de conhecimento (carregada dos arquivos com fonte) ----------

-- Árvore das regiões do corpo. Cada região aponta para a região "mãe" (autorrelacionamento).
CREATE TABLE T_TAMI_REGIAO (
    CD_REGIAO      VARCHAR2(30)  NOT NULL,
    CD_REGIAO_PAI  VARCHAR2(30),
    NM_REGIAO      VARCHAR2(60)  NOT NULL,
    NR_NIVEL       NUMBER(1)     NOT NULL,
    DS_PALAVRAS    VARCHAR2(800),
    CONSTRAINT PK_TAMI_REGIAO PRIMARY KEY (CD_REGIAO),
    CONSTRAINT FK_TAMI_REGIAO_PAI FOREIGN KEY (CD_REGIAO_PAI) REFERENCES T_TAMI_REGIAO (CD_REGIAO),
    CONSTRAINT CK_TAMI_REGIAO_NIVEL CHECK (NR_NIVEL BETWEEN 0 AND 3)
);

-- Sinais de alerta e condições comuns, cada um com destino e fonte oficial.
CREATE TABLE T_TAMI_SINAL (
    CD_SINAL       VARCHAR2(20)  NOT NULL,
    DS_TIPO        VARCHAR2(10)  NOT NULL,
    DS_POPULAR     VARCHAR2(600) NOT NULL,
    DS_TERMO       VARCHAR2(300),
    DS_DESTINO     VARCHAR2(20)  NOT NULL,
    DS_VALE_PARA   VARCHAR2(300),
    DS_FONTE       VARCHAR2(200),
    DS_FONTE_URL   VARCHAR2(400),
    ST_REVISAR     CHAR(1)       DEFAULT 'S' NOT NULL,
    CONSTRAINT PK_TAMI_SINAL PRIMARY KEY (CD_SINAL),
    CONSTRAINT CK_TAMI_SINAL_TIPO CHECK (DS_TIPO IN ('SINAL', 'CONDICAO')),
    CONSTRAINT CK_TAMI_SINAL_DESTINO CHECK (DS_DESTINO IN ('SAMU_192', 'UPA_HOJE', 'UBS_EM_BREVE', 'CUIDADO_EM_CASA')),
    CONSTRAINT CK_TAMI_SINAL_REVISAR CHECK (ST_REVISAR IN ('S', 'N'))
);

-- As formas populares de dizer cada sinal ("braço dormente", "nao sinto o braco"...).
CREATE TABLE T_TAMI_EXPRESSAO (
    ID_EXPRESSAO   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CD_SINAL       VARCHAR2(20)  NOT NULL,
    DS_EXPRESSAO   VARCHAR2(300) NOT NULL,
    CONSTRAINT PK_TAMI_EXPRESSAO PRIMARY KEY (ID_EXPRESSAO),
    CONSTRAINT FK_TAMI_EXPRESSAO_SINAL FOREIGN KEY (CD_SINAL) REFERENCES T_TAMI_SINAL (CD_SINAL) ON DELETE CASCADE
);

-- Em que regiões do corpo cada sinal faz sentido (N:N).
CREATE TABLE T_TAMI_SINAL_REGIAO (
    CD_SINAL       VARCHAR2(20)  NOT NULL,
    CD_REGIAO      VARCHAR2(30)  NOT NULL,
    CONSTRAINT PK_TAMI_SINAL_REGIAO PRIMARY KEY (CD_SINAL, CD_REGIAO),
    CONSTRAINT FK_TAMI_SR_SINAL FOREIGN KEY (CD_SINAL) REFERENCES T_TAMI_SINAL (CD_SINAL) ON DELETE CASCADE,
    CONSTRAINT FK_TAMI_SR_REGIAO FOREIGN KEY (CD_REGIAO) REFERENCES T_TAMI_REGIAO (CD_REGIAO) ON DELETE CASCADE
);

-- ---------- Uso do app ----------

CREATE TABLE T_TAMI_USUARIO (
    ID_USUARIO         NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NM_USUARIO         VARCHAR2(80)  NOT NULL,
    DS_CONTATO         VARCHAR2(120) NOT NULL,
    ST_CONSENT_SAUDE   CHAR(1)       DEFAULT 'N' NOT NULL,
    DT_CONSENTIMENTO   TIMESTAMP,
    DT_CADASTRO        TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_TAMI_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UN_TAMI_USUARIO_CONTATO UNIQUE (DS_CONTATO),
    CONSTRAINT CK_TAMI_USUARIO_CONSENT CHECK (ST_CONSENT_SAUDE IN ('S', 'N'))
);

-- "Pessoas que eu cuido": o próprio usuário, um filho, a mãe...
CREATE TABLE T_TAMI_PESSOA (
    ID_PESSOA        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO       NUMBER        NOT NULL,
    NM_APELIDO       VARCHAR2(60)  NOT NULL,
    DS_RELACAO       VARCHAR2(20)  NOT NULL,
    NR_IDADE_MESES   NUMBER(4)     NOT NULL,
    ST_GESTANTE      CHAR(1)       DEFAULT 'N' NOT NULL,
    ST_DIABETES      CHAR(1)       DEFAULT 'N' NOT NULL,
    DT_CADASTRO      TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    DT_ATUALIZACAO   TIMESTAMP,
    CONSTRAINT PK_TAMI_PESSOA PRIMARY KEY (ID_PESSOA),
    CONSTRAINT FK_TAMI_PESSOA_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES T_TAMI_USUARIO (ID_USUARIO) ON DELETE CASCADE,
    CONSTRAINT CK_TAMI_PESSOA_RELACAO CHECK (DS_RELACAO IN ('EU', 'FILHO', 'MAE', 'PAI', 'AVO', 'PARCEIRO', 'OUTRO')),
    CONSTRAINT CK_TAMI_PESSOA_IDADE CHECK (NR_IDADE_MESES BETWEEN 0 AND 1500),
    CONSTRAINT CK_TAMI_PESSOA_GESTANTE CHECK (ST_GESTANTE IN ('S', 'N')),
    CONSTRAINT CK_TAMI_PESSOA_DIABETES CHECK (ST_DIABETES IN ('S', 'N'))
);

-- Uma conversa com a Tami. Sem a permissão de dados de saúde, o relato e as respostas não são guardados.
CREATE TABLE T_TAMI_CONVERSA (
    ID_CONVERSA          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO           NUMBER,
    ID_PESSOA            NUMBER,
    NR_IDADE_MESES       NUMBER(4)     NOT NULL,
    ST_GUARDAR           CHAR(1)       DEFAULT 'N' NOT NULL,
    DS_RELATO            VARCHAR2(4000),
    CD_REGIAO            VARCHAR2(30),
    NR_SINAIS_TOTAL      NUMBER(6),
    NR_SINAIS_REGIAO     NUMBER(6),
    DS_QUEIXA            VARCHAR2(10),
    DT_INICIO            TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
    DT_FIM               TIMESTAMP,
    DS_DESTINO           VARCHAR2(20),
    DS_PRIORIDADE_UBS    VARCHAR2(20),
    CD_MENSAGEM          VARCHAR2(40),
    ST_CRISE             CHAR(1)       DEFAULT 'N' NOT NULL,
    ST_POR_NAO_SEI       CHAR(1)       DEFAULT 'N' NOT NULL,
    NR_PERGUNTAS         NUMBER(3)     DEFAULT 0 NOT NULL,
    CONSTRAINT PK_TAMI_CONVERSA PRIMARY KEY (ID_CONVERSA),
    CONSTRAINT FK_TAMI_CONVERSA_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES T_TAMI_USUARIO (ID_USUARIO) ON DELETE CASCADE,
    CONSTRAINT FK_TAMI_CONVERSA_PESSOA FOREIGN KEY (ID_PESSOA) REFERENCES T_TAMI_PESSOA (ID_PESSOA) ON DELETE SET NULL,
    CONSTRAINT FK_TAMI_CONVERSA_REGIAO FOREIGN KEY (CD_REGIAO) REFERENCES T_TAMI_REGIAO (CD_REGIAO),
    CONSTRAINT CK_TAMI_CONVERSA_DESTINO CHECK (DS_DESTINO IS NULL OR DS_DESTINO IN ('SAMU_192', 'UPA_HOJE', 'UBS_EM_BREVE', 'CUIDADO_EM_CASA')),
    CONSTRAINT CK_TAMI_CONVERSA_GUARDAR CHECK (ST_GUARDAR IN ('S', 'N')),
    CONSTRAINT CK_TAMI_CONVERSA_CRISE CHECK (ST_CRISE IN ('S', 'N')),
    CONSTRAINT CK_TAMI_CONVERSA_NAO_SEI CHECK (ST_POR_NAO_SEI IN ('S', 'N'))
);

-- Cada pergunta respondida, na ordem.
CREATE TABLE T_TAMI_RESPOSTA (
    ID_RESPOSTA     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_CONVERSA     NUMBER         NOT NULL,
    NR_ORDEM        NUMBER(3)      NOT NULL,
    CD_PERGUNTA     VARCHAR2(30)   NOT NULL,
    DS_PERGUNTA     VARCHAR2(1000),
    DS_RESPOSTA     VARCHAR2(1000),
    DS_ORIGEM       VARCHAR2(10)   NOT NULL,
    ST_NAO_SEI      CHAR(1)        DEFAULT 'N' NOT NULL,
    DT_RESPOSTA     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_TAMI_RESPOSTA PRIMARY KEY (ID_RESPOSTA),
    CONSTRAINT FK_TAMI_RESPOSTA_CONVERSA FOREIGN KEY (ID_CONVERSA) REFERENCES T_TAMI_CONVERSA (ID_CONVERSA) ON DELETE CASCADE,
    CONSTRAINT CK_TAMI_RESPOSTA_ORIGEM CHECK (DS_ORIGEM IN ('USUARIO', 'TEXTO', 'HERDADA')),
    CONSTRAINT CK_TAMI_RESPOSTA_NAO_SEI CHECK (ST_NAO_SEI IN ('S', 'N'))
);

-- As regras que levaram ao destino: cada orientação pode ser explicada.
CREATE TABLE T_TAMI_REGRA_ACIONADA (
    ID_REGRA        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_CONVERSA     NUMBER         NOT NULL,
    CD_REGRA        VARCHAR2(60)   NOT NULL,
    DS_DESTINO      VARCHAR2(20)   NOT NULL,
    DS_MOTIVO       VARCHAR2(300),
    CONSTRAINT PK_TAMI_REGRA_ACIONADA PRIMARY KEY (ID_REGRA),
    CONSTRAINT FK_TAMI_REGRA_CONVERSA FOREIGN KEY (ID_CONVERSA) REFERENCES T_TAMI_CONVERSA (ID_CONVERSA) ON DELETE CASCADE
);

-- "Onde dói?" e a escala de 0 a 10.
CREATE TABLE T_TAMI_DOR (
    ID_DOR          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_CONVERSA     NUMBER         NOT NULL,
    CD_REGIAO       VARCHAR2(30)   NOT NULL,
    DS_LADO         VARCHAR2(10),
    NR_NIVEL        NUMBER(2)      NOT NULL,
    DS_TIPO         VARCHAR2(30),
    DT_REGISTRO     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_TAMI_DOR PRIMARY KEY (ID_DOR),
    CONSTRAINT FK_TAMI_DOR_CONVERSA FOREIGN KEY (ID_CONVERSA) REFERENCES T_TAMI_CONVERSA (ID_CONVERSA) ON DELETE CASCADE,
    CONSTRAINT FK_TAMI_DOR_REGIAO FOREIGN KEY (CD_REGIAO) REFERENCES T_TAMI_REGIAO (CD_REGIAO),
    CONSTRAINT CK_TAMI_DOR_NIVEL CHECK (NR_NIVEL BETWEEN 0 AND 10),
    CONSTRAINT CK_TAMI_DOR_LADO CHECK (DS_LADO IS NULL OR DS_LADO IN ('DIREITO', 'ESQUERDO', 'MEIO'))
);

-- "Isso te ajudou?" (uma por conversa; pode ser atualizada).
CREATE TABLE T_TAMI_FEEDBACK (
    ID_FEEDBACK     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_CONVERSA     NUMBER         NOT NULL,
    DS_AVALIACAO    VARCHAR2(15)   NOT NULL,
    DS_COMENTARIO   VARCHAR2(1000),
    DT_FEEDBACK     TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    DT_ATUALIZACAO  TIMESTAMP,
    CONSTRAINT PK_TAMI_FEEDBACK PRIMARY KEY (ID_FEEDBACK),
    CONSTRAINT UN_TAMI_FEEDBACK_CONVERSA UNIQUE (ID_CONVERSA),
    CONSTRAINT FK_TAMI_FEEDBACK_CONVERSA FOREIGN KEY (ID_CONVERSA) REFERENCES T_TAMI_CONVERSA (ID_CONVERSA) ON DELETE CASCADE,
    CONSTRAINT CK_TAMI_FEEDBACK_AVALIACAO CHECK (DS_AVALIACAO IN ('SIM', 'MAIS_OU_MENOS', 'NAO'))
);

CREATE INDEX IX_TAMI_EXPRESSAO_SINAL ON T_TAMI_EXPRESSAO (CD_SINAL);
CREATE INDEX IX_TAMI_SR_REGIAO ON T_TAMI_SINAL_REGIAO (CD_REGIAO);
CREATE INDEX IX_TAMI_PESSOA_USUARIO ON T_TAMI_PESSOA (ID_USUARIO);
CREATE INDEX IX_TAMI_CONVERSA_USUARIO ON T_TAMI_CONVERSA (ID_USUARIO);
CREATE INDEX IX_TAMI_CONVERSA_DESTINO ON T_TAMI_CONVERSA (DS_DESTINO);
CREATE INDEX IX_TAMI_RESPOSTA_CONVERSA ON T_TAMI_RESPOSTA (ID_CONVERSA);
CREATE INDEX IX_TAMI_REGRA_CONVERSA ON T_TAMI_REGRA_ACIONADA (ID_CONVERSA);
